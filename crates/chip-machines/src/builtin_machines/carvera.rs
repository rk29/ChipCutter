const SHANK_EIGHTH_MM: f64 = 3.175;
const ESSENTIAL_EXTENDED_VENDOR: &str = "Makera (Essential Milling Bit Set - Extended)";

#[derive(Debug, Clone, Copy)]
enum MakeraTier {
    Carvera,
    CarveraAir,
    CarveraZ1,
}

impl MakeraTier {
    const fn id_prefix(self) -> &'static str {
        match self {
            Self::Carvera => "carvera_atc",
            Self::CarveraAir => "carvera",
            Self::CarveraZ1 => "carvera_z1",
        }
    }

    const fn product_prefix(self) -> &'static str {
        match self {
            Self::Carvera => "MAKERA-ATC",
            Self::CarveraAir => "MAKERA",
            Self::CarveraZ1 => "MAKERA-Z1",
        }
    }

    const fn pick<T: Copy>(self, carvera: T, air: T, z1: T) -> T {
        match self {
            Self::Carvera => carvera,
            Self::CarveraAir => air,
            Self::CarveraZ1 => z1,
        }
    }

    fn tool_id(self, suffix: &str) -> ToolId {
        ToolId(format!("{}_{suffix}", self.id_prefix()))
    }

    fn product_id(self, suffix: &str) -> String {
        format!("{}-{suffix}", self.product_prefix())
    }

    #[allow(clippy::too_many_arguments)]
    fn preset(
        self,
        id_suffix: &str,
        name: &str,
        material: &str,
        diameter_mm: f64,
        flutes: u32,
        surface_speed_m_min: (f64, f64, f64),
        chipload_mm_tooth: (f64, f64, f64),
        default_stepdown_mm: (f64, f64, f64),
        default_stepover_mm: (f64, f64, f64),
        coolant_override: Option<CoolantMode>,
    ) -> CuttingPreset {
        let id = format!("{}_{id_suffix}", self.id_prefix());
        CuttingPreset::from_surface_speed(SurfaceSpeedPresetSpec {
            id: &id,
            name,
            material,
            diameter_mm,
            flutes,
            surface_speed_m_min: self.pick(
                surface_speed_m_min.0,
                surface_speed_m_min.1,
                surface_speed_m_min.2,
            ),
            chipload_mm_tooth: self.pick(
                chipload_mm_tooth.0,
                chipload_mm_tooth.1,
                chipload_mm_tooth.2,
            ),
            default_stepdown_mm: self.pick(
                default_stepdown_mm.0,
                default_stepdown_mm.1,
                default_stepdown_mm.2,
            ),
            default_stepover_mm: self.pick(
                default_stepover_mm.0,
                default_stepover_mm.1,
                default_stepover_mm.2,
            ),
            coolant_override,
        })
    }

    #[allow(clippy::too_many_arguments)]
    fn tool(
        self,
        tool_number: u32,
        id_suffix: &str,
        name: &str,
        product_suffix: &str,
        default_coolant: CoolantMode,
        stickout_length_mm: f64,
        geometry: CutterGeometry,
        presets: Vec<CuttingPreset>,
    ) -> Tool {
        Tool {
            id: self.tool_id(id_suffix),
            tool_number,
            length_offset_number: tool_number,
            diameter_offset_number: tool_number,
            name: name.to_string(),
            vendor: Some(ESSENTIAL_EXTENDED_VENDOR.to_string()),
            product_id: Some(self.product_id(product_suffix)),
            native_unit: DisplayUnit::Millimeter,
            spindle_direction: SpindleDirection::Cw,
            default_coolant,
            stickout_length_mm,
            geometry,
            presets,
        }
    }
}

